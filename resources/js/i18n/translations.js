export function useTranslation(locale = 'hi') {
    const lang = translations[locale] ? locale : 'hi';
    const dict = translations[lang];

    const t = (key, fallback = '') => {
        return dict[key] || fallback || key;
    };

    return { t, locale: lang };
}
